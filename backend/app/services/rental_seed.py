def bootstrap(rstore: Any) -> None:
    """用计费引擎把示例账单补齐（延迟导入，避免模块初始化环）。"""
    from datetime import datetime

    from app.services.rental_billing import (
        DEPOSIT_FULL,
        apply_payment,
        create_deposit_bill,
        create_refund_bill,
        generate_rent_bills,
        recalc_on_term_change,
    )

    items = {int(row["id"]): row for row in rstore.items}

    # 每台设备登记时收押金
    for item in rstore.items:
        create_deposit_bill(item, batch_no="YD-20260616-REGISTER")

    # ---- 租赁单 1：9 月 15 日批次退租并结算 --------------------------
    for item_id, payments in ((1, {"2026-06": 3000, "2026-07": 6000, "2026-08": 4000}),
                              (2, {"2026-06": 6000, "2026-07": 12000, "2026-08": 10000})):
        item = items[item_id]
        bills = generate_rent_bills(
            item, item["实际退租日期"], batch_no="JS-20260915-SEED",
            remarks="9 月 15 日批次退租结算",
        )
        for bill in bills:
            pay = payments.get(bill["账期月份"], 0)
            if pay:
                apply_payment(bill, Decimal(str(pay)), at="2026-09-16 15:00")
        refund = create_refund_bill(item, batch_no="JS-20260915-SEED")
        if item_id == 2 and refund is not None:
            # EQ-102 押金已退清
            apply_payment(refund, abs(refund["金额"]), at="2026-09-17 10:00")

    # ---- 租赁单 2：EQ-201 先按旧约定结算，后改租重算 ----------------
    item = items[4]
    item["起租日期"] = date(2026, 5, 1)
    item["到期日期"] = date(2026, 8, 31)
    item["月租金额"] = Decimal("8000.00")
    old_bills = generate_rent_bills(
        item, date(2026, 8, 15), batch_no="JS-20260815-SEED",
        remarks="8 月 15 日退租，按原约定结算",
    )
    # 旧账单 5/6/7 月已全额收款，8 月未收
    for bill in old_bills:
        if bill["账期月份"] in ("2026-05", "2026-06", "2026-07"):
            apply_payment(bill, bill["金额"], at="2026-08-16 09:00")
    # 8 月 25 日补充协议生效：到期日改 8 月 10 日、月租调 9000，重算已出账单
    item["起租日期"] = date(2026, 5, 1)
    item["到期日期"] = date(2026, 8, 10)
    item["月租金额"] = Decimal("9000.00")
    recalc_on_term_change(item, change_seq=1)
    # 押金按改租后的最新口径退（尚未实际支付）
    create_refund_bill(item, batch_no="CG-20260825-SEED", remarks="按租期变更后口径重算应退押金")

    # EQ-202 在租，无租金账单；时间戳仅为统一字段风格
    _ = datetime
